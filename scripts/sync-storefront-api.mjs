// Regenerates the storefront's typed Convex API from the functions that are
// currently deployed, then writes it into the storefront repo.
//
//   npm run api:sync             dev deployment (keep `npx convex dev` running)
//   npm run api:sync -- --prod   production deployment
//
// The storefront is expected next to this repo. Override with STOREFRONT_DIR.
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";

const storefrontDir = resolve(
  process.env.STOREFRONT_DIR ?? "../stumar-maspindzeli-storefront",
);
if (!existsSync(join(storefrontDir, "package.json"))) {
  console.error(`Storefront not found at ${storefrontDir}. Set STOREFRONT_DIR.`);
  process.exit(1);
}

const target = join(storefrontDir, "lib", "convex", "api.ts");
const tmp = join(tmpdir(), `convex-api-${Date.now()}.ts`);
const passThrough = process.argv.slice(2).join(" ");

execSync(`npx convex-helpers ts-api-spec --output-file "${tmp}" ${passThrough}`, {
  stdio: "inherit",
});

const banner = `/* eslint-disable */
/**
 * AUTO-GENERATED by \`npm run api:sync\` in the admin repo (stumarmaspindzeli).
 * Typed references to the public Convex functions. Do not edit by hand.
 */
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, banner + readFileSync(tmp, "utf8"));
rmSync(tmp, { force: true });
console.log(`Storefront API updated: ${target}`);
